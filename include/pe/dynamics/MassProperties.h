#pragma once
//==============================================================================
// pe/dynamics/MassProperties.h
//
// 质量、质心、转动惯量张量 —— 由形状和密度解析计算。
//
//------------------------------------------------------------------------------
// 惯量张量是干什么的
//------------------------------------------------------------------------------
// 平动里 F = m*a，质量是一个标量：不管从哪个方向推，同样的力给同样的加速度。
// 转动里 tau = I*alpha，**I 是一个 3x3 矩阵**，因为"绕哪根轴转"会影响难易程度：
// 一根长杆绕自身轴线旋转很容易，绕垂直方向翻滚就费劲得多。
//
// 惯量张量就是把这种方向依赖性编码进一个矩阵。它的对角元是绕三根坐标轴的
// 转动惯量，非对角元（惯量积）描述"绕 X 施加力矩却会引起绕 Y 的转动"这种耦合。
//
// 引擎里的每种形状都关于三个坐标平面对称，所以**惯量积全为零**，
// 局部空间的惯量张量是对角阵。这带来两个好处：求逆只是三个分量取倒数，
// 而且存储和调试都直观。（加入 ConvexHull 之后就不再成立了，届时要做特征分解
// 或者直接用完整矩阵 —— 现有接口已经是 Mat3，不用改。）
//
//------------------------------------------------------------------------------
// 为什么要有 invMass / invInertia 而不是 mass / inertia
//------------------------------------------------------------------------------
// 求解器里出现的永远是 `1/m` 和 `I^-1`，从来不是 m 和 I 本身。存倒数有两个好处：
//   1. 热循环里省掉除法（除法比乘法慢好几倍，而求解器每帧要跑几万次）
//   2. **静态物体可以用 invMass = 0 表示"无穷大质量"**，不需要任何特判分支。
//      施加冲量的公式 `v += impulse * invMass` 在 invMass = 0 时自动变成
//      "速度不变"，正是静态物体该有的行为。这个技巧让整个求解器不用写
//      `if (isStatic)`。
//==============================================================================

#include "pe/collision/Shape.h"
#include "pe/core/Types.h"
#include "pe/math/Mat3.h"
#include "pe/math/Vec3.h"

namespace pe {

//------------------------------------------------------------------------------
// 常用密度（kg/m^3）。取的是现实中的近似值，需要手感优先时随便改。
//------------------------------------------------------------------------------
namespace densities {
inline constexpr real kWater = real(1000);
inline constexpr real kWood = real(700);
inline constexpr real kConcrete = real(2400);
inline constexpr real kSteel = real(7850);
/// 游戏里的默认密度。取比水轻一点，让箱子推起来不至于太沉。
inline constexpr real kDefault = real(500);
}  // namespace densities

//------------------------------------------------------------------------------
// 质量属性
//------------------------------------------------------------------------------
struct MassProperties {
    real mass;

    /// 质心，**局部空间**。
    ///
    /// 当前恒为零向量：Shape.h 定下的约定是"形状的局部原点就是它的几何中心"，
    /// 而均匀密度物体的质心就是几何中心。留着这个字段是为了将来 ——
    /// 一个刚体挂多个碰撞体时（M8 的复合形状），合成质心就不在原点了。
    Vec3 centerOfMass;

    /// 关于**质心**的惯量张量，局部空间。
    Mat3 inertia;

    MassProperties() = default;

    /// 惯量张量的逆。当前形状的惯量张量都是对角阵，但接口按一般矩阵写，
    /// 免得将来加 ConvexHull 时要改调用点。
    Mat3 InverseInertia() const noexcept;

    /// 质量的倒数；mass <= 0 时返回 0（表示无穷大质量，见文件头）。
    real InverseMass() const noexcept {
        return mass > real(0) ? real(1) / mass : real(0);
    }

    /// 保持形状不变，把总质量缩放到指定值。
    ///
    /// 惯量张量与质量成正比（I = ∫ r^2 dm），所以按同一个比例缩放即可。
    /// 用途：美术给的箱子尺寸不能改，但设计想要"这个箱子推起来轻一点"。
    MassProperties WithMass(real newMass) const noexcept;
};

//------------------------------------------------------------------------------
// 计算
//------------------------------------------------------------------------------

/// 按形状和均匀密度算出质量属性。
/// 退化形状（半径为 0 等）会得到质量 0 与零惯量张量，而不是 NaN。
MassProperties ComputeMassProperties(const Shape& shape, real density) noexcept;

/// 按形状和指定总质量算出质量属性（密度反推）。
/// 游戏里通常这样用 —— 设计师说的是"这个箱子 20 公斤"，不是"密度 500"。
MassProperties ComputeMassPropertiesFromMass(const Shape& shape, real mass) noexcept;

//------------------------------------------------------------------------------
// 平行轴定理
//------------------------------------------------------------------------------

/// 把关于质心的惯量张量搬到"偏移 offset 处的平行轴"上。
///
///     I_new = I_com + m * (|d|^2 * E - d ⊗ d)
///
/// 标量版本 `I = I_com + m*d^2` 只对绕单根轴成立；三维版本必须写成这个形式，
/// 因为沿 d 方向那根轴的转动惯量**不该**增加（绕自己平移的方向转，
/// 质量分布没变）—— 括号里那一项在 d 方向上恰好为零，正是这个道理。
///
/// 用途：M8 让一个刚体挂多个碰撞体时，把每个碰撞体的惯量搬到公共质心上再相加。
Mat3 TranslateInertia(const Mat3& inertiaAboutCom, real mass,
                      const Vec3& offset) noexcept;

/// 把惯量张量旋转到另一个坐标系：`I' = R * I * R^T`。
///
/// 每帧要用它把局部惯量张量转到世界空间（见 Integrator.h）。
/// 两边都要乘是因为惯量张量是**二阶张量**，不是向量 ——
/// 只乘一个 R 得到的东西没有物理意义。
Mat3 RotateInertia(const Mat3& inertia, const Mat3& rotation) noexcept;

}  // namespace pe
