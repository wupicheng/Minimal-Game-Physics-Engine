#pragma once
//==============================================================================
// pe/dynamics/Integrator.h
//
// 半隐式欧拉积分器（Semi-implicit / Symplectic Euler）。
//
//------------------------------------------------------------------------------
// 为什么必须拆成两个函数
//------------------------------------------------------------------------------
// 积分不是一步做完的，中间要留出求解器的位置：
//
//     IntegrateVelocity(dt)     // 重力、外力、阻尼 -> 新速度
//     ---- 求解器在这里直接改 v、w ----
//     IntegratePosition(dt)     // 用**求解后**的速度更新位姿
//
// 这个顺序正是"半隐式"的含义，也是它和显式欧拉的全部区别：
//
//     显式欧拉：  x += v_old * dt;  v += a * dt        <- 用旧速度更新位置
//     半隐式：    v += a * dt;      x += v_new * dt    <- 用新速度更新位置
//
// 一行之差，行为天差地别。显式欧拉对简谐运动（弹簧、轨道、任何往复系统）
// **系统能量单调增长**，物体会越弹越高直到数值爆炸。半隐式是辛（symplectic）
// 积分器，它精确保守的是一个与真实能量相差 O(dt) 的"影子能量"，
// 所以真实能量只在真值附近有界振荡，永远不会发散。
//
// 而且它与冲量法天然契合：求解器直接改速度，改完位置积分立刻就能用上，
// 不需要重新求力、也不需要迭代整个时间步。
//
//------------------------------------------------------------------------------
// 陀螺项
//------------------------------------------------------------------------------
// 角速度的更新不是简单的 `w += I^-1 * tau * dt`，还有一项：
//
//     w += I_world^-1 * (tau - w x (I_world * w)) * dt
//                              ^^^^^^^^^^^^^^^^^ 陀螺项（欧拉方程）
//
// 它来自"角动量 L = I*w 在世界空间守恒，但 I 随姿态旋转而变化"这个事实。
// 少了它，自由旋转的长条物体角动量不守恒，翻滚会不自然
// （网球拍定理 / Dzhanibekov 效应那种绕中间轴翻转的现象就完全消失）。
//
// 代价是陀螺项在高速自旋下会让显式积分不稳定，所以下面对它做了限幅，
// 详见 Integrator.cpp。
//==============================================================================

#include "pe/core/Types.h"
#include "pe/dynamics/RigidBody.h"
#include "pe/math/Vec3.h"

namespace pe {

/// 默认重力（米/秒^2）。取现实值 9.81。
///
/// 顺带一提：几乎所有 FPS 都用**大于**现实的重力（CS 是 800 单位/秒^2，
/// 换算下来约 20 m/s^2），因为现实重力下的跳跃在屏幕上显得又慢又飘。
/// 这是手感参数，交给游戏侧在 WorldConfig 里定，引擎只给一个物理正确的默认值。
inline constexpr Vec3 kDefaultGravity = Vec3(real(0), real(-9.81), real(0));

//------------------------------------------------------------------------------
// 阶段 A：积分速度（求解器之前）
//------------------------------------------------------------------------------

/// 施加重力、累积外力与阻尼，更新线速度与角速度。
/// 静态体和休眠体不受影响。运动学体也不受影响 —— 它的速度由游戏逻辑说了算。
void IntegrateVelocity(RigidBody& body, const Vec3& gravity, real dt) noexcept;

//------------------------------------------------------------------------------
// 阶段 B：积分位置（求解器之后）
//------------------------------------------------------------------------------

/// 用当前速度更新位置与姿态，并刷新 invInertiaWorld。
/// 运动学体**会**被积分位置（这正是它和静态体的唯一区别）。
void IntegratePosition(RigidBody& body, real dt) noexcept;

//------------------------------------------------------------------------------
// 辅助
//------------------------------------------------------------------------------

/// 由当前姿态刷新世界空间惯量张量的逆：`I_world^-1 = R * I_local^-1 * R^T`。
///
/// 任何直接改写 rotation 的地方（传送、编辑器拖拽、网络同步）都必须跟着调它，
/// 否则求解器会拿着上一帧姿态的惯量算冲量。IntegratePosition 内部已经调过了。
void UpdateWorldInertia(RigidBody& body) noexcept;

/// 清零累积外力。每帧 Step 的最后一步。
///
/// 之所以要显式清零而不是"用完即弃"：`ApplyForce` 的语义是"这一帧持续施加"，
/// 游戏逻辑每帧调用它。不清零的话力会无限累积，物体会加速到飞出地图。
inline void ClearForces(RigidBody& body) noexcept {
    body.force = Vec3::Zero();
    body.torque = Vec3::Zero();
}

/// 更新休眠状态。返回 true 表示这一帧刚刚睡着。
///
/// 判据是"线速度和角速度**同时**低于阈值持续 timeToSleep 秒"。
/// 任何一项超标都会把计时器清零重新计 —— 一个绕着自己慢慢转的箱子不该被判定
/// 为静止。
bool UpdateSleep(RigidBody& body, real dt, const SleepConfig& config) noexcept;

//------------------------------------------------------------------------------
// 渲染插值
//------------------------------------------------------------------------------

/// 在两个位姿之间插值，alpha ∈ [0,1]。
///
/// **固定步长物理 + 可变帧率渲染必须做这件事**。物理以 1/60 秒定步长推进，
/// 显示器可能是 144Hz，也可能这一帧渲染慢了、物理连跑了两步。直接拿物理位姿
/// 去渲染，画面会有肉眼可见的抖动（时间走样 / temporal aliasing）。
///
/// 正确做法是保留上一帧的位姿，用"距离下一次物理步还差多少"作为 alpha 插值。
/// 位置用线性插值，姿态用 Slerp。
Transform InterpolateTransform(const Transform& previous, const Transform& current,
                               real alpha) noexcept;

}  // namespace pe
