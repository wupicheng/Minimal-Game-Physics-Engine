#pragma once
//==============================================================================
// pe/dynamics/Material.h
//
// 表面材质：摩擦系数与恢复系数。
//
//------------------------------------------------------------------------------
// 为什么材质在 dynamics 而不是 collision
//------------------------------------------------------------------------------
// 摩擦和弹性描述的是"碰撞之后怎么运动"，是纯粹的动力学属性。碰撞层只回答
// "碰在哪儿、有多深"（见 ARCHITECTURE.md §2），它不需要、也不应该知道材质。
// 求解器（M7）在 Prepare 阶段把两侧材质组合成接触约束的参数。
//
//------------------------------------------------------------------------------
// 两个系数的物理含义
//------------------------------------------------------------------------------
// - **恢复系数** e（restitution）：分离速度 / 接近速度。
//   0 = 完全非弹性（落地就贴住），1 = 完全弹性（弹回原高度，能量不损失）。
//   FPS 里绝大多数东西取 0~0.2；手雷取 0.4 左右才有"弹一下"的手感。
//
// - **摩擦系数** mu（Coulomb friction）：最大静摩擦力 / 法向力。
//   它不是"阻力"，而是一个**上限** —— 切向冲量的大小不能超过 mu 乘以法向冲量，
//   超过就开始滑动。这个约束在求解器里表现为对切向冲量做投影。
//
//------------------------------------------------------------------------------
// 组合规则：为什么不是简单相加
//------------------------------------------------------------------------------
// 一次碰撞涉及两个材质，必须合成一个值。业界的事实标准是：
//   - 摩擦取**几何平均** sqrt(mu_a * mu_b)
//   - 恢复取**最大值** max(e_a, e_b)
//
// 摩擦取几何平均而不是算术平均，是因为它有一条重要性质：任何一方是 0（理想冰面）
// 时结果就是 0。算术平均做不到这一点 —— 冰面配橡胶还能得到 0.5 的摩擦，
// 那就没有"完全光滑的表面"这个概念了。
//
// 恢复取最大值而不是平均，是为了让"超级弹力球"这个设定成立：一个 e=1 的球
// 砸到 e=0 的地面，玩家期待它弹起来，而不是被地面吸收掉。
// 换句话说，这两条规则都是**让极端材质的意图能够生效**。
//==============================================================================

#include "pe/core/Types.h"
#include "pe/math/MathUtil.h"

namespace pe {

struct Material {
    /// 摩擦系数，>= 0。0 = 完全光滑；1 附近 = 橡胶；超过 1 物理上也合法
    /// （表示"比自身重量还大的抓地力"，赛车轮胎就是）。
    real friction;

    /// 恢复系数，[0, 1]。大于 1 会凭空产生能量，模拟会发散。
    real restitution;

    Material() = default;

    constexpr Material(real f, real e) noexcept : friction(f), restitution(e) {}

    /// 默认材质：中等摩擦、几乎不弹。适合大多数场景道具。
    static constexpr Material Default() noexcept {
        return Material(real(0.5), real(0.05));
    }

    //--------------------------------------------------------------------------
    // 几个常用预设。数值是手感调出来的，不是查表来的物理常数 ——
    // 游戏里的"真实"是玩家觉得对，不是和现实一致。
    //--------------------------------------------------------------------------

    /// 冰面：几乎没有摩擦。
    static constexpr Material Ice() noexcept { return Material(real(0.05), real(0.05)); }

    /// 木箱：摩擦大、不弹。堆叠场景的默认选择。
    static constexpr Material Wood() noexcept { return Material(real(0.6), real(0.1)); }

    /// 金属：摩擦中等，弹一点。
    static constexpr Material Metal() noexcept { return Material(real(0.4), real(0.2)); }

    /// 橡胶 / 弹力球：摩擦大、很弹。手雷用这个。
    static constexpr Material Rubber() noexcept { return Material(real(0.9), real(0.7)); }
};

//------------------------------------------------------------------------------
// 组合
//
// 求解器在 Prepare 阶段对每个接触点调一次。理由见文件头。
//------------------------------------------------------------------------------

/// 几何平均。任何一方为 0，结果就是 0。
inline real CombineFriction(const Material& a, const Material& b) noexcept {
    const real product = a.friction * b.friction;
    return product > real(0) ? Sqrt(product) : real(0);
}

/// 取最大值，让"弹力球"这类设定能生效。
inline constexpr real CombineRestitution(const Material& a, const Material& b) noexcept {
    return Max(a.restitution, b.restitution);
}

}  // namespace pe
