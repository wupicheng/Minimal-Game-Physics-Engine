#pragma once
//==============================================================================
// pe/core/Types.h
//
// 引擎全局的标量类型别名、数学常量与容差。所有其它头文件的最底层依赖。
//
// 设计要点：
//   - 标量类型统一用 `real` 别名。将来若要换成 double（例如做大世界坐标），
//     只需要改这一行，整个引擎跟着走。所有字面量都必须写成 real(1.5) 的形式，
//     不能直接写 1.5f，否则换类型时会静默产生精度截断。
//   - 各种容差常量集中在这里，而不是散落在算法内部的魔法数字里。
//     调参（比如堆叠抖动、休眠太早）时只需要看这一个文件。
//==============================================================================

#include <cstddef>
#include <cstdint>

namespace pe {

//------------------------------------------------------------------------------
// 标量类型
//------------------------------------------------------------------------------

/// 引擎中所有物理量的标量类型。换成 double 只改这一行。
using real = float;

//------------------------------------------------------------------------------
// 数学常量
//------------------------------------------------------------------------------

inline constexpr real kPi     = real(3.14159265358979323846);
inline constexpr real kTwoPi  = kPi * real(2.0);
inline constexpr real kHalfPi = kPi * real(0.5);

/// 通用浮点比较容差。float 的机器精度约 1.2e-7，取 1e-6 留一个数量级的余量。
inline constexpr real kEpsilon = real(1e-6);

/// 归一化时的长度平方下限。低于这个值认为向量是零向量，直接返回零而不是产生 NaN。
/// 用长度的平方是为了省一次 sqrt。
inline constexpr real kNormalizeEpsilonSq = real(1e-12);

//------------------------------------------------------------------------------
// 物理容差（求解器/碰撞检测调参入口）
//
// 这几个值是"允许多少误差"的工程折中，不是物理常数。调参时优先动这里。
//------------------------------------------------------------------------------

/// 允许的接触穿透量（米）。求解器不会把穿透推到 0，而是推到这个值附近。
/// 为什么要留：如果要求穿透严格为 0，物体在完美接触状态下会因浮点噪声反复
/// "碰撞—分离—碰撞"，表现为肉眼可见的高频抖动。留一点点重叠反而稳定。
inline constexpr real kLinearSlop = real(0.005);

/// 宽相位 AABB 的膨胀量（米）。物体在这个膨胀壳内移动时不需要重建空间结构。
inline constexpr real kAabbMargin = real(0.05);

//------------------------------------------------------------------------------
// 句柄 / 索引
//------------------------------------------------------------------------------

/// 无效索引。Handle 用它表示"空句柄"。
inline constexpr std::uint32_t kInvalidIndex = 0xFFFFFFFFu;

//------------------------------------------------------------------------------
// 刚体类型
//------------------------------------------------------------------------------

/// 刚体的运动学类别。决定它是否被积分、是否参与求解、能否被推动。
enum class BodyType : std::uint8_t {
    /// 永不移动（墙、地面）。invMass = 0，不积分。静态-静态对在宽相位就被丢弃。
    Static = 0,
    /// 由游戏逻辑直接设定位置/速度（电梯、移动平台、被脚本控制的门）。
    /// invMass = 0，所以碰撞时它推动别人，别人推不动它，但它自己会移动。
    Kinematic = 1,
    /// 完全由物理模拟驱动。
    Dynamic = 2,
};

//------------------------------------------------------------------------------
// 碰撞过滤
//
// 两个碰撞体 A、B 会被检测，当且仅当：
//     (A.layer & B.layerMask) != 0  &&  (B.layer & A.layerMask) != 0
// 即"双方都同意"。单向同意不算，避免出现 A 能撞 B、B 撞不到 A 的不对称行为。
//------------------------------------------------------------------------------

using LayerMask = std::uint32_t;

inline constexpr LayerMask kLayerNone = 0u;
inline constexpr LayerMask kLayerAll  = 0xFFFFFFFFu;

/// FPS 常用的几个层。游戏侧可以自行扩展到 32 层。
namespace layers {
inline constexpr LayerMask kDefault   = 1u << 0;  ///< 普通道具、箱子
inline constexpr LayerMask kWorld     = 1u << 1;  ///< 静态地图几何
inline constexpr LayerMask kPlayer    = 1u << 2;  ///< 角色胶囊
inline constexpr LayerMask kProjectile= 1u << 3;  ///< 抛射物
inline constexpr LayerMask kTrigger   = 1u << 4;  ///< 触发区域
}  // namespace layers

}  // namespace pe
