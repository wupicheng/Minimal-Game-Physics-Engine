#pragma once
//==============================================================================
// pe/solver/ContactConstraint.h
//
// 接触约束：把一个 Manifold（几何）+ 两个刚体（动力学）+ 两份材质，
// 变成求解器可以迭代的形式。
//
//------------------------------------------------------------------------------
// 一个接触点上有三个约束
//------------------------------------------------------------------------------
//   1. 法向：相对法向速度 >= 0（不再互相靠近）。**不等式**约束 ——
//      冲量只能推开、不能拉住，所以累积冲量要钳在 >= 0。
//   2、3. 两个切向：相对切向速度 = 0（不滑动）。等式约束，但冲量受库仑锥限制
//      |lambda_t| <= mu * lambda_n —— 超过上限就开始滑动，钳制正是这个物理。
//
//------------------------------------------------------------------------------
// 核心公式
//------------------------------------------------------------------------------
// 接触点处的相对速度（B 相对 A）：
//
//     dv = (vB + wB x rB) - (vA + wA x rA)
//
// 沿法线的分量 Cdot = Dot(dv, n)。要施加冲量 lambda*n 使它变成目标值，
// 需要知道"约束空间的等效质量" k：
//
//     k = invMassA + invMassB
//       + Dot(n, Cross(invIA * Cross(rA, n), rA))
//       + Dot(n, Cross(invIB * Cross(rB, n), rB))
//
// 前两项是平动的贡献，后两项是转动的贡献 —— 它们回答"在 rA 处沿 n 推一下，
// 这个点会沿 n 动多快"，力臂越长、惯量越小，动得越多，等效质量就越小。
// 于是 lambda = -(Cdot + bias) / k。
//
//------------------------------------------------------------------------------
// 最容易写错的地方：钳制的是**累积**冲量
//------------------------------------------------------------------------------
// 直觉写法是"每次迭代算出 lambda，钳到非负，施加"。**这是错的**。
//
// 正确做法是记住这个接触点从本帧开始累积的总冲量 P，每次迭代：
//     P_new = max(0, P_old + lambda)
//     实际施加 (P_new - P_old)
//
// 区别在于：迭代过程中某一步算出的 lambda 可以是**负的**（撤销之前施加过头的
// 冲量），只要总量还是非负就合法。按直觉写法把每步都钳成非负，就永远无法回退，
// 多个接触点之间会互相顶死，堆叠收敛不了 —— 表现是箱子堆越叠越抖。
//==============================================================================

#include <cstdint>

#include "pe/collision/Manifold.h"
#include "pe/dynamics/Material.h"
#include "pe/dynamics/RigidBody.h"
#include "pe/solver/IConstraint.h"

namespace pe {

//------------------------------------------------------------------------------
// 单个接触点的求解状态
//------------------------------------------------------------------------------
struct ContactConstraintPoint {
    Vec3 rA;  ///< 从 A 的质心指向接触点
    Vec3 rB;

    /// 法向等效质量的**倒数**（也就是上面那个 1/k）。
    /// 存倒数是为了让迭代里只有乘法。
    real normalMass;
    real tangentMass[2];

    /// 本帧累积的冲量。这三个值会被写回接触缓存，下一帧作为 warm start 的初值。
    real normalImpulse;
    real tangentImpulse[2];

    /// 目标法向速度的偏置：Baumgarte 位置修正 + 恢复系数，两项都在 Prepare 里算好。
    real velocityBias;

    real penetration;
    std::uint32_t featureId;  ///< 跨帧匹配用，来自 Manifold
};

//------------------------------------------------------------------------------
// 接触约束
//
// 每帧重建（几何每帧都在变），只有累积冲量通过 featureId 从缓存里继承。
// 刻意**不**继承虚接口，理由见 IConstraint.h：接触约束数量大、结构同质，
// 走具体类型的紧凑循环。
//------------------------------------------------------------------------------
struct ContactConstraint {
    /// 求解期间指向刚体存储。约定：`Solve()` 执行期间不得创建/销毁刚体，
    /// 否则底层 vector 扩容会让这两个指针悬垂。
    /// PhysicsWorld 的 Step() 是唯一的调用者，它保证这一点。
    RigidBody* bodyA;
    RigidBody* bodyB;

    Vec3 normal;      ///< 由 A 指向 B（继承 Manifold 的约定）
    Vec3 tangent[2];  ///< 与 normal 构成正交基，由 BuildOrthonormalBasis 生成

    real friction;
    real restitution;

    /// 上层给的稳定标识，用来在接触缓存里找到上一帧的同一对。
    /// PhysicsWorld 会把 (colliderA, colliderB) 打包进来。
    std::uint64_t pairKey;

    std::uint8_t pointCount;
    ContactConstraintPoint points[4];

    //--------------------------------------------------------------------------
    // 三段式求解
    //--------------------------------------------------------------------------

    /// 由几何和材质算出等效质量与偏置项。每帧一次。
    void Prepare(const SolverConfig& config, real dt) noexcept;

    /// 施加继承来的累积冲量作为初始猜测。每帧一次，在迭代之前。
    void WarmStart() noexcept;

    /// 一次迭代：先解摩擦，再解法向。
    ///
    /// 顺序是刻意的。摩擦的上限 `mu * normalImpulse` 要用到法向冲量，
    /// 先解摩擦意味着用的是**上一次迭代**的法向冲量 —— 略微滞后，但更稳定。
    /// 反过来先解法向的话，法向冲量在本次迭代内被改大，摩擦上限跟着变大，
    /// 两者会互相放大，接触点多的时候容易震荡。
    void SolveVelocity() noexcept;

    real MaxPenetration() const noexcept;
};

//------------------------------------------------------------------------------
// 构造
//------------------------------------------------------------------------------

/// 由流形、两个刚体、两份材质造出接触约束。
/// 不做 Prepare —— 那需要 dt，由求解器统一调用。
ContactConstraint MakeContactConstraint(RigidBody* bodyA, RigidBody* bodyB,
                                        const Manifold& manifold,
                                        const Material& materialA,
                                        const Material& materialB,
                                        std::uint64_t pairKey) noexcept;

}  // namespace pe
