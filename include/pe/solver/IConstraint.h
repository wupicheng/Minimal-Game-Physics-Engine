#pragma once
//==============================================================================
// pe/solver/IConstraint.h
//
// 约束的抽象接口。
//
//------------------------------------------------------------------------------
// 什么是"约束"
//------------------------------------------------------------------------------
// 约束是对刚体状态的一条限制，写成一个标量函数 C(x) 以及它对时间的导数 Cdot。
// 求解器要做的是：施加冲量，让 Cdot 满足要求。
//
//   - **接触约束**：C = 穿透深度，Cdot = 接触点处的相对法向速度。
//     要求 Cdot >= 0（不再互相靠近），是**不等式**约束，所以冲量只能是单向的。
//   - **距离约束**（绳索）：C = |pA - pB| - L，要求 Cdot = 0，是等式约束。
//   - **铰链**（门）：把相对运动限制在一根轴上，是若干个等式约束的组合。
//
// 三者的求解结构完全一样：算出约束空间的等效质量、算出当前的违反量、
// 施加冲量、把累积冲量钳到合法范围。所以抽象成一个接口是自然的。
//
//------------------------------------------------------------------------------
// 为什么接触约束**不**走这个虚接口
//------------------------------------------------------------------------------
// 一帧里接触约束有几百上千个，而关节（门、绳索）只有个位数。让接触也走虚函数，
// 每个接触点每次迭代都要付一次间接跳转 —— 8 次迭代 x 1000 个接触点 x 3 个方向，
// 这个开销是实打实的，而且虚函数会挡住向量化。
//
// 所以分成两条路：
//   - `ContactConstraint` 是**具体类型**，求解器对它开一个紧凑的循环
//   - 其它约束实现 `IConstraint`，求解器在同一轮迭代里顺带调它们
//
// 这不是"抽象没做好"，而是**按数量分层**：多而同质的走数据导向，
// 少而异质的走多态。两者在求解循环里是并列的，迭代次数与顺序完全一致。
//==============================================================================

#include "pe/core/Types.h"

namespace pe {

//------------------------------------------------------------------------------
// 求解器参数
//
// 这几个值全是工程折中，不是物理常数。调堆叠稳定性、调"物体陷得深不深"，
// 都从这里下手。
//------------------------------------------------------------------------------
struct SolverConfig {
    /// 速度迭代次数。
    ///
    /// 顺序冲量是 Gauss-Seidel 迭代：一次只解一个接触点，解完立刻更新速度，
    /// 后面的点用的是更新过的值。这样收敛快，但也意味着**单次迭代不够** ——
    /// 解完最后一个点，第一个点可能又被破坏了。8 次是画质与耗时的常见折中：
    /// 4 次以下堆叠会软，16 次以上收益已经很小。
    int velocityIterations = 8;

    /// Baumgarte 位置修正系数 beta，取值 (0, 1]。
    ///
    /// 每帧把穿透量的 beta 倍转化成分离速度。取 1 会一帧内推平，
    /// 但那部分速度是**凭空加进系统的能量**，物体会被弹开（"爆开"）。
    /// 取 0.2 意味着每帧消掉两成穿透，几帧内平滑收敛，加入的能量小到看不出来。
    real baumgarte = real(0.2);

    /// 允许残留的穿透量（米）。低于它的穿透不做修正。
    ///
    /// 为什么要留：要求穿透严格为 0 的话，物体在完美接触状态下会因浮点噪声
    /// 反复"碰撞—分离—碰撞"，表现为肉眼可见的高频抖动。留一点点重叠反而稳定。
    real linearSlop = kLinearSlop;

    /// 单帧位置修正的速度上限（米/秒）。
    ///
    /// 防"爆开"：物体生成时嵌在墙里 1 米深，没有这个上限的话
    /// Baumgarte 会给它 (0.2 * 1 / dt) = 12 m/s 的分离速度，直接弹飞。
    real maxLinearCorrection = real(3);

    /// 恢复系数的启用阈值（米/秒）。
    ///
    /// 接近速度低于它就当作 e = 0。没有这个阈值的话，静止在地面上的物体会因为
    /// 每帧重力带来的那一丁点接近速度而永远微微弹跳，永远睡不着。
    /// 取 1 m/s：比"一帧重力"（9.81/60 ≈ 0.16 m/s）大一个数量级。
    real restitutionThreshold = real(1);

    /// 是否启用 warm starting（把上一帧的累积冲量作为这一帧的初值）。
    ///
    /// 关掉它主要是为了做对照实验 —— 堆叠会立刻变软、明显下陷。
    /// 生产环境没有理由关。
    bool warmStarting = true;
};

//------------------------------------------------------------------------------
// IConstraint
//
// 三段式，对应求解器每帧的三个阶段。M7 只有接触约束（走具体类型的快路径），
// 这个接口是给未来的关节预留的：门、绳索、载具悬挂都只是新增一个实现类，
// 求解循环本身一行都不用改。
//------------------------------------------------------------------------------
class IConstraint {
public:
    virtual ~IConstraint() = default;

    /// 每帧一次：算出约束空间的等效质量、偏置项等只依赖当前位姿的量。
    /// 把它和迭代分开，是因为这些量在迭代过程中不变，算一次就够。
    virtual void Prepare(const SolverConfig& config, real dt) = 0;

    /// 每帧一次，在迭代之前：施加上一帧的累积冲量作为初始猜测。
    ///
    /// 这是堆叠稳定性的关键。物理直觉是：一摞箱子的受力状态每帧几乎不变，
    /// 上一帧解出来的冲量已经很接近这一帧的答案了。从它出发，几次迭代就能收敛；
    /// 从零出发，8 次迭代只够把最下面那个箱子撑起来一部分，于是每帧下陷一点点。
    virtual void WarmStart() = 0;

    /// 每次迭代一次：施加冲量把约束往满足的方向推。
    virtual void SolveVelocity() = 0;
};

}  // namespace pe
