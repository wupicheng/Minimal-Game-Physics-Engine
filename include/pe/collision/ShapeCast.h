#pragma once
//==============================================================================
// pe/collision/ShapeCast.h
//
// 形状扫掠：把一个凸形状沿一段位移"扫"过去，求它最先撞到什么。
//
//------------------------------------------------------------------------------
// 它解决的两个问题
//------------------------------------------------------------------------------
// 1. **隧穿**。离散模拟用的是每帧末的位置，一个高速抛射物（火箭、手雷）一帧移动
//    的距离可能超过墙的厚度，于是两帧之间它就在墙的两侧，中间那一下谁也没看见。
//    这正是 M2 的 UPGRADE_NOTES 里标着 P0 的那一条。
//    （hitscan 子弹不受影响 —— 它本来就是一条射线。）
//
// 2. **角色移动**。角色控制器不参与刚体模拟，它靠的是"先问能走多远、再走过去"。
//    没有形状扫掠就只能"先穿进去再推出来"，那种做法在贴墙、上台阶、走斜坡时
//    会不停抖动，手感是坏的。
//
//------------------------------------------------------------------------------
// 算法：保守推进（Conservative Advancement）
//------------------------------------------------------------------------------
// 朴素做法是把位移切成很多小段逐段测重叠，但步长取多小都可能漏，而且慢。
//
// 保守推进的思路是**用距离换步长**：如果两个形状当前相距 d，而沿位移方向它们
// 每单位时间最多靠近 v，那么至少 d/v 这么长的时间里绝不可能相撞 —— 可以放心
// 一步跳过去。跳完再问一次距离，如此反复。距离越近步子越小，最终收敛到接触点。
//
//     t = 0
//     循环：
//         d, 最近点对 = ConvexDistance(形状在 t 处, 目标)
//         若 d < 容差            -> 命中，返回 t
//         approach = Dot(位移, 从我指向目标的单位方向)   // 每单位 t 靠近多少
//         若 approach <= 0       -> 越走越远，永远撞不上
//         t += d / approach
//         若 t > 1               -> 走完全程也没撞上
//
// 它**不会漏报**（每一步都是严格保守的），而且对凸形状收敛很快 ——
// 实测正面撞击 3~5 轮、掠射 10 轮以内。
//
// 之所以现在能写出来，是因为 M5 的 `ConvexDistance()` 提供了"任意两个凸形状之间
// 的距离与最近点对"—— 那正是这个算法唯一需要的输入。M2 当时做不了，
// 缺的就是这个。
//==============================================================================

#include "pe/collision/Shape.h"
#include "pe/core/Types.h"
#include "pe/math/Transform.h"
#include "pe/math/Vec3.h"

namespace pe {

//------------------------------------------------------------------------------
// 扫掠命中结果
//------------------------------------------------------------------------------
struct ShapeCastHit {
    /// 命中发生在位移的多大比例处，取值 [0, 1]。
    /// 起点就已经重叠时为 0。乘上位移长度就是"能安全走多远"。
    real fraction;

    /// 接触点，世界空间。
    Vec3 point;

    /// 被撞表面的外法线，单位向量，**朝向扫掠形状来的一侧**。
    /// 与 `RaycastHit::normal` 的约定一致，可以直接拿来做贴墙滑行
    /// （`v -= Dot(v, n) * n`）。
    Vec3 normal;

    /// 起点处两个形状就已经重叠。
    ///
    /// 这时 fraction 为 0、normal 是**脱困方向**（沿它把扫掠形状推出去），
    /// point 是接触点。角色控制器靠这个字段把"生成时卡在墙里"的情况解掉。
    bool startPenetrating;

    /// 起点重叠时的穿透深度（米）。沿 normal 推这么远就恰好脱开。
    /// `startPenetrating` 为 false 时恒为 0 —— 调用方不需要额外判断。
    real depth;
};

//------------------------------------------------------------------------------
// 扫掠
//------------------------------------------------------------------------------

/// 把 moving（位姿 start）沿 displacement 扫向静止的 target。
///
/// 返回 false 表示整段位移都没碰到东西，此时 out 未定义。
///
/// **扫掠过程中形状不旋转**，只平移。旋转扫掠（一边转一边动）要复杂得多，
/// 而且游戏里几乎用不到：角色是竖直胶囊不转，抛射物用球体近似。
bool ShapeCast(const Shape& moving, const Transform& start, const Vec3& displacement,
               const Shape& target, const Transform& targetTransform,
               ShapeCastHit& out) noexcept;

/// 保守推进的迭代上限。实测正面撞击 3~5 轮收敛，掠射（几乎平行擦过）最慢，
/// 10 轮以内也够了。这个数是保险丝。
inline constexpr int kShapeCastMaxIterations = 32;

/// 判定"贴上了"的距离容差（米）。
///
/// 取 kLinearSlop 的一半：比求解器允许的穿透量更严，这样扫掠停下来的位置
/// 一定还没进入求解器会去修正的范围，两者不会互相打架。
/// 同时它也让扫掠的结果**略微保守**（停得比真实接触点早一点点），
/// 这正是角色控制器想要的 —— 贴墙时留一条缝，下一帧不会立刻判定为重叠。
inline constexpr real kShapeCastTolerance = kLinearSlop * real(0.5);

}  // namespace pe
