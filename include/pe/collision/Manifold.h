#pragma once
//==============================================================================
// pe/collision/Manifold.h
//
// 接触流形（contact manifold）：窄相位的输出，"两个形状怎么碰在一起的"。
//
//------------------------------------------------------------------------------
// 为什么不是"一个接触点"
//------------------------------------------------------------------------------
// 一个箱子平躺在地上，几何上的接触是**一整个面**。如果只报一个点，求解器就只能
// 在那一个点上施加冲量，箱子会绕着那个点翻跟头 —— 表现是"箱子放地上会自己转起来
// 然后倒下"。必须报出这个面上的若干个点，冲量分摊在它们之间，才能形成阻止旋转的
// 力偶。
//
// 上限取 4 个：一个凸面与另一个凸面的交集是凸多边形，它的四个"最外围"的顶点
// 已经能张出整个支撑区域；再多的点提供的约束是冗余的，只会拖慢求解器。
//
//------------------------------------------------------------------------------
// 这里**没有**什么，以及为什么
//------------------------------------------------------------------------------
// 架构文档 §3 最初的草图里，Manifold 还带着 `ColliderHandle a, b`、
// `friction / restitution`、以及每个接触点上的 `normalImpulse / tangentImpulse`。
// 实现时把它们全部移出去了，理由是架构文档 §2 自己定下的那条规矩：
//
//     collision 层不知道质量、速度的存在，只吐几何结果。
//
//   - **摩擦/恢复系数**是材质属性。窄相位要么得去读材质（跨层），要么把这两个
//     字段留着不填 —— 而"结构里躺着一个没人负责填的字段"正是 Ray.h 里痛斥过的
//     那种迟早会不一致的设计。它们属于 M7 的 ContactConstraint。
//   - **累积冲量**是求解器的迭代状态，跨帧继承（warm starting）也是求解器的事。
//     窄相位每帧从零开始算几何，让它捎带一份求解器状态没有任何道理。
//     M7 的接触缓存按 featureId 把上一帧的冲量匹配回来即可 —— 这正是
//     `featureId` 存在的全部意义。
//   - **句柄**：和 RaycastHit 完全同一个理由（见 Ray.h）。纯几何结果不带身份，
//     World 层（M8）在外面包一层 `ContactPair { ColliderHandle a, b; Manifold m; }`。
//   - **切向基 tangent[2]**：`Vec3.h` 的 `BuildOrthonormalBasis(n, t1, t2)` 已经
//     能由 normal 现算，存一份只是让两份数据有机会不一致。求解器 Prepare 的时候
//     算一次就好。
//
// 换来的好处是 Manifold 是一个**纯 POD、可平凡拷贝、语义完全自洽**的几何结果，
// 和 RaycastHit 处在同一个抽象层次上。
//==============================================================================

#include <cstdint>

#include "pe/core/Types.h"
#include "pe/math/MathUtil.h"
#include "pe/math/Vec3.h"

namespace pe {

//------------------------------------------------------------------------------
// 单个接触点
//------------------------------------------------------------------------------
struct ContactPoint {
    /// 接触点的世界坐标。
    ///
    /// 约定：取**两个见证点的中点**。所谓见证点是 A 上最深入 B 的那个点
    /// 和 B 上最深入 A 的那个点，它们相距正好 penetration。取中点而不是取某一侧，
    /// 是为了让 Collide(A,B) 和 Collide(B,A) 得到完全相同的接触点 ——
    /// 这条对称性被测试钉死，它能抓住一大类"分派时把 A/B 弄反"的错误。
    Vec3 position;

    /// 穿透深度，**正值**表示重叠。沿 normal 把 B 推开这么多（或把 A 推开）
    /// 就恰好分离。
    ///
    /// 允许是很小的负值：宽相位用 fat AABB 提前产生候选对，所以窄相位有机会
    /// 在真正接触之前就报出"即将接触"的点。求解器需要这种提前量来做 warm start。
    /// 具体多小算"还要保留"由窄相位的 kSpeculativeMargin 决定。
    real penetration;

    /// 特征 ID：这个接触点是由"哪两个几何特征"（面/边/顶点）生成的。
    ///
    /// 它唯一的用途是**跨帧匹配**：下一帧重新算出流形之后，按 featureId 找到
    /// 上一帧的同一个接触点，把累积冲量继承过来（warm starting）。
    /// 没有它，堆叠的箱子每帧都要从零开始重新收敛，肉眼可见地下陷再弹回。
    ///
    /// 只要求"同一处接触在相邻帧里给出同一个值"，不要求全局唯一，
    /// 也不要求有任何可读的含义。
    std::uint32_t featureId;
};

//------------------------------------------------------------------------------
// 接触流形
//------------------------------------------------------------------------------
struct Manifold {
    /// 接触法线，单位向量，**方向约定：由 A 指向 B**。
    ///
    /// 也就是说：沿 +normal 移动 B（或沿 -normal 移动 A）会让两者分离。
    /// 这条约定必须全引擎统一，否则符号错误会表现成"碰撞时物体互相吸进去"。
    /// 分派函数 Collide() 保证无论调用方按什么顺序传入 A、B，这条约定都成立。
    Vec3 normal;

    /// 有效接触点数量，0 到 4。为 0 表示没有接触。
    std::uint8_t pointCount;

    ContactPoint points[4];

    Manifold() = default;

    /// 置为"没有接触"。所有窄相位函数在返回 false 之前都会调它，
    /// 这样调用方哪怕忘了看返回值，读到的也是一个自洽的空流形，而不是上一次的残留。
    void Clear() noexcept {
        normal = Vec3::Zero();
        pointCount = 0;
    }

    bool IsColliding() const noexcept { return pointCount > 0; }

    /// 追加一个接触点。超过 4 个时直接丢弃 —— 调用方（面裁剪）负责在之前
    /// 就把点精简到 4 个以内，所以走到这一步说明是调用方的 bug，
    /// 但丢弃比越界写坏内存好。
    void AddPoint(const Vec3& position, real penetration,
                  std::uint32_t featureId) noexcept {
        if (pointCount >= 4) return;
        ContactPoint& cp = points[pointCount++];
        cp.position = position;
        cp.penetration = penetration;
        cp.featureId = featureId;
    }

    /// 最深的那个接触点的深度。角色控制器判断"陷得有多深"时用。
    real MaxPenetration() const noexcept {
        real m = real(0);
        for (std::uint8_t i = 0; i < pointCount; ++i) {
            m = Max(m, points[i].penetration);
        }
        return m;
    }
};

//------------------------------------------------------------------------------
// 辅助
//------------------------------------------------------------------------------

/// 打包一个 featureId。四个字节的含义由生成它的那个算法自己定义
/// （比如盒-盒会填入 参考盒是谁 / 参考面编号 / 入射面编号 / 裁剪后的顶点序号）。
inline constexpr std::uint32_t MakeFeatureId(std::uint8_t a, std::uint8_t b,
                                             std::uint8_t c, std::uint8_t d) noexcept {
    return (static_cast<std::uint32_t>(a) << 24) |
           (static_cast<std::uint32_t>(b) << 16) |
           (static_cast<std::uint32_t>(c) << 8) | static_cast<std::uint32_t>(d);
}

// 摩擦需要的切向基不在这里 —— `Vec3.h` 里的 `BuildOrthonormalBasis(n, t1, t2)`
// 已经提供了，而且用的是 Erin Catto 那个永不退化的构造。M7 的求解器在 Prepare
// 阶段直接调它即可，不要在 Manifold 里再存一份。

}  // namespace pe
