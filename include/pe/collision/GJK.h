#pragma once
//==============================================================================
// pe/collision/GJK.h
//
// GJK（Gilbert–Johnson–Keerthi）：任意凸形状之间的距离与相交判定。
//
//------------------------------------------------------------------------------
// 核心思想
//------------------------------------------------------------------------------
// 两个凸集 A、B 的**闵可夫斯基差** D = A ⊖ B = { a - b | a ∈ A, b ∈ B } 也是凸集，
// 而且有一条漂亮的性质：
//
//     A 与 B 相交  <=>  D 包含原点
//     A 与 B 的距离 = 原点到 D 的距离
//
// 于是"两个形状的距离"被化简成了"一个凸集到一个点的距离"。
//
// D 的顶点数是 A、B 顶点数的乘积，显式构造它是不可能的。GJK 的精髓在于
// **完全不构造 D**，只通过支撑函数按需采样：
//
//     support_D(d) = support_A(d) - support_B(-d)
//
// 算法维护一个最多 4 个顶点的单纯形（点/线段/三角形/四面体），每轮：
//   1. 求单纯形上离原点最近的点 v
//   2. 朝 -v（从 v 指向原点）的方向取一个新的支撑点 w
//   3. 若 w 没能比 v 更靠近原点，说明已经到边界了 -> D 不含原点，距离 = |v|
//   4. 否则把 w 加进单纯形，约简掉对"最近点"没有贡献的顶点，回到 1
// 单纯形一旦成为包住原点的四面体，就说明相交。
//
//------------------------------------------------------------------------------
// 关键实现决定：GJK 只跑在"核"上，半径事后再加
//------------------------------------------------------------------------------
// 球是"一个点外扩半径"，胶囊是"一条线段外扩半径"。如果让支撑函数把半径也算进去，
// GJK 就要在**曲面**上迭代 —— 曲面没有顶点，支撑点每轮都在微微移动，收敛会明显
// 变慢，EPA 更是要在球面上堆出成百上千个三角形才能达到精度。
//
// 所以这里的支撑函数只返回**核**（sphere -> 圆心，capsule -> 轴线端点，
// box -> 角点），半径由 CoreRadius() 单独给出，在算完距离之后再减：
//
//     真实距离   = 核距离 - rA - rB
//     真实穿透   = rA + rB - 核距离       （核不相交时）
//                = 核穿透 + rA + rB       （核相交时，核穿透由 EPA 给出）
//
// 好处是：核全都是**多面体**（点、线段、凸多面体），支撑函数只在有限个顶点里挑，
// GJK 能精确地在有限步内终止；而且球/胶囊之间的碰撞根本用不到 EPA ——
// 它们的核不相交时距离就够了。这也正是 Bullet 的 margin 机制在做的事。
//==============================================================================

#include "pe/collision/Shape.h"
#include "pe/core/Types.h"
#include "pe/math/Transform.h"
#include "pe/math/Vec3.h"

namespace pe {

//------------------------------------------------------------------------------
// 凸形状代理
//
// 它是一个**临时的栈上对象**，不是要存起来的数据。这一点很重要：
// 将来加入 ConvexHull 时，这里可以直接放一个指向顶点池的裸指针
// （`const Vec3* hullVertices` + 顶点数），而 `Shape` 本身仍然是不含指针的 POD
// —— 由调用方在查询开始时把 hullIndex 解析成指针，填进这个代理里。
// 这就是"POD 存储 + 瞬时代理"的分工，两边都不用妥协。
//------------------------------------------------------------------------------
struct ConvexProxy {
    Shape shape;
    Transform transform;

    ConvexProxy() = default;
    ConvexProxy(const Shape& s, const Transform& t) noexcept : shape(s), transform(t) {}

    /// 核在世界空间方向 dir 上的支撑点（**不含**半径外扩）。
    /// dir 不需要是单位向量，只有方向有意义。
    Vec3 SupportCore(const Vec3& dir) const noexcept;

    /// 核需要外扩多少才能还原成真正的形状。box 是 0，球/胶囊是它们的半径。
    real CoreRadius() const noexcept;
};

//------------------------------------------------------------------------------
// GJK 结束时的单纯形
//
// 除了闵可夫斯基差上的点 w，还要记住它是由 A、B 上的哪两个支撑点相减得来的
// （pa、pb）。有了它们才能把重心坐标反算回两个形状表面上的**见证点**，
// 而见证点正是接触点位置的来源。EPA 也要靠这一份对应关系。
//------------------------------------------------------------------------------
struct GjkSimplex {
    Vec3 w[4];   ///< 闵可夫斯基差 A ⊖ B 上的点，w[i] = pa[i] - pb[i]
    Vec3 pa[4];  ///< A 的核上的支撑点
    Vec3 pb[4];  ///< B 的核上的支撑点
    int count;
};

enum class GjkStatus {
    /// 两个核不相交。distance / pointA / pointB 有效。
    Separated,
    /// 两个核相交（原点落在闵可夫斯基差内部）。要拿穿透深度请接着跑 EPA。
    Intersecting,
    /// 迭代次数用尽仍未收敛。实践中只会在极端退化的输入上出现；
    /// 此时按 Separated 的字段读取当前最好的估计，误差通常在容差量级。
    MaxIterations,
};

struct GjkResult {
    GjkStatus status;
    real distance;  ///< 两个**核**之间的距离（相交时为 0）
    Vec3 pointA;    ///< A 的核上离 B 最近的点
    Vec3 pointB;    ///< B 的核上离 A 最近的点
    GjkSimplex simplex;
    int iterations;
};

/// GJK 距离查询。
///
/// 注意 pointA / pointB 是**核**上的点，不含半径。要还原到真实表面，
/// 沿 (pointB - pointA) 的单位方向各自外扩 CoreRadius() 即可。
GjkResult Gjk(const ConvexProxy& a, const ConvexProxy& b) noexcept;

/// GJK 迭代次数上限。核都是多面体，理论上有限步必然终止；
/// 这个上限是为浮点误差导致的循环兜底的。
inline constexpr int kGjkMaxIterations = 64;

/// 相对收敛容差。判据写成相对形式（乘上 |v|^2）而不是绝对值，
/// 这样在 1 毫米和 100 米两种尺度的场景里表现一致。
inline constexpr real kGjkTolerance = real(1e-6);

}  // namespace pe
