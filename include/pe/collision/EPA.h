#pragma once
//==============================================================================
// pe/collision/EPA.h
//
// EPA（Expanding Polytope Algorithm，扩张多面体算法）：求穿透深度与分离法线。
//
//------------------------------------------------------------------------------
// 为什么必须要有 EPA
//------------------------------------------------------------------------------
// GJK 只回答"相不相交"。一旦相交，原点落在闵可夫斯基差 D 的内部，
// "原点到 D 的距离"变成 0，GJK 就再也给不出任何信息了 ——
// 可它给不出的恰恰是求解器最需要的东西：**最小平移向量（MTV）**，
// 即"把两个物体分开最省力的方向和距离"。
//
// 那个量在 D 上的定义是：原点到 D **边界**的最短距离，以及对应的方向。
// EPA 就是专门去找它的。
//
//------------------------------------------------------------------------------
// 算法
//------------------------------------------------------------------------------
// 拿 GJK 结束时那个包住原点的四面体当初始多面体，然后反复"往外顶"：
//
//   1. 在多面体的所有三角面里，找**离原点最近**的那一个，法线 n、距离 d
//   2. 朝 n 取一个新的支撑点 w
//   3. 若 Dot(w, n) - d 小于容差，说明 D 在这个方向上已经没有更外面的东西了
//      -> 这个面就贴在 D 的边界上，收敛，答案就是 (n, d)
//   4. 否则把 w 加进来：删掉所有"能被 w 看见"的面（Dot(n_face, w - 面上一点) > 0），
//      留下的空洞边界叫**地平线**（horizon），把 w 与地平线上每条边连成新的三角面
//   5. 回到 1
//
// 每一轮多面体都严格变大、且始终包含在 D 里，最近面的距离单调不减并收敛到
// 真实的穿透深度。这是一个从内部逼近的过程 —— 和 GJK 从外部逼近正好相反。
//
//------------------------------------------------------------------------------
// 什么时候会用到它
//------------------------------------------------------------------------------
// 因为 GJK/EPA 都只跑在**核**上（见 GJK.h），球和胶囊的核是点和线段，
// 它们之间几乎不可能真的相交 —— 所以球/胶囊的碰撞全都在 GJK 那一步就出结果了。
// EPA 实际只会被两类情况触发：
//   - 盒 vs 盒 重叠
//   - 胶囊的轴线插进了盒子里
// 这也意味着 EPA 不在最热的路径上，可读性优先于极致优化。
//==============================================================================

#include "pe/collision/GJK.h"
#include "pe/core/Types.h"
#include "pe/math/Vec3.h"

namespace pe {

struct EpaResult {
    /// false 表示没能得出结果（初始单纯形退化到连四面体都撑不起来，
    /// 典型情况是两个球的核完全重合）。此时其余字段无意义，
    /// 调用方需要自己兜底。
    bool valid;

    /// 分离法线，单位向量，**由 A 指向 B**（与 Manifold 的约定一致）。
    /// 沿 -normal 移动 A（或沿 +normal 移动 B）depth 那么远，两个核恰好分离。
    Vec3 normal;

    /// **核**的穿透深度（不含半径）。调用方要自己加上 CoreRadius()。
    real depth;

    Vec3 pointA;  ///< A 的核上最深入 B 的那个点
    Vec3 pointB;  ///< B 的核上最深入 A 的那个点
};

/// simplex 必须来自一次返回 Intersecting 的 GJK 调用。
/// 顶点数不足 4 时，内部会先想办法把它撑成四面体；撑不起来就返回 valid = false。
EpaResult Epa(const ConvexProxy& a, const ConvexProxy& b,
              const GjkSimplex& simplex) noexcept;

/// EPA 的迭代上限。实践中十几轮就收敛，这个数是纯粹的保险丝。
inline constexpr int kEpaMaxIterations = 48;

/// 收敛容差（米）。新支撑点比当前最近面外凸不到这个量就认为贴边了。
inline constexpr real kEpaTolerance = real(1e-5);

}  // namespace pe
